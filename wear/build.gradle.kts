android {
    namespace = "com.example.ethos.wear"
    compileSdk = 35

    defaultConfig {
        // Must match the phone app so both can talk over the Wearable Data Layer.
        applicationId = "com.example.ethos"
        minSdk = 30
        targetSdk = 35
        versionCode = 2
        versionName = "1.1.0"
    }

    // Same key as the phone app (keystore.properties in the project root, not in git).
    val keystoreFile = rootProject.file("keystore.properties")
    val signing = if (keystoreFile.exists()) {
        val props = Properties().apply { keystoreFile.inputStream().use { load(it) } }
        signingConfigs.create("release") {
            storeFile = rootProject.file(props.getProperty("storeFile"))
            storePassword = props.getProperty("storePassword")
            keyAlias = props.getProperty("keyAlias")
            keyPassword = props.getProperty("keyPassword")
        }
    } else null

    buildTypes {
        release {
            isMinifyEnabled = false
            signingConfig = signing
        }
    }
